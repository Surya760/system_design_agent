"""
Complete System Design Specification Document model.
"""
from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
import re
from typing import Any, Dict, List, Optional
import uuid

from system_design_agent.models.domain import (
    HLDSection,
    LLDSection,
    RequirementsSection,
    ResilienceSection,
    ScaffoldingSection,
    ValidationReport,
)


@dataclass
class SystemDesignSpec:
    title: str
    pitch: str
    id: str = field(default_factory=lambda: str(uuid.uuid4()))
    created_at: str = field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    target_dau: int = 50_000

    requirements: RequirementsSection = field(default_factory=RequirementsSection)
    hld: HLDSection = field(default_factory=HLDSection)
    lld: LLDSection = field(default_factory=LLDSection)
    resilience: ResilienceSection = field(default_factory=ResilienceSection)
    scaffolding: ScaffoldingSection = field(default_factory=ScaffoldingSection)

    validation_report: ValidationReport = field(default_factory=ValidationReport)
    tokens_used: int = 0
    duration_seconds: float = 0.0

    def generate_slug(self) -> str:
        clean = re.sub(r"[^a-zA-Z0-9\s-]", "", self.title).strip().lower()
        return re.sub(r"[\s_-]+", "-", clean) or f"spec-{self.id[:8]}"

    def to_markdown(self) -> str:
        """Assembles the full 5-section specification into GitHub-flavored Markdown."""
        parts = [
            f"# Technical Specification: {self.title}",
            "",
            "> **Document Type:** Production Engineering Blueprint (HLD + LLD)  ",
            f"> **Target Baseline Scale:** ~{self.target_dau:,} Daily Active Users (DAU)  ",
            f"> **Specification ID:** `{self.id}`  ",
            f"> **Generated At:** {self.created_at}  ",
            "",
            "## Executive Summary & Raw Pitch",
            f"{self.pitch.strip()}",
            "",
            "---",
            "",
            "## 1. Requirements & Core Assumptions",
            self.requirements.raw_markdown.strip() or "_Section generation pending_",
            "",
            "---",
            "",
            "## 2. High-Level Design (HLD)",
            self.hld.raw_markdown.strip() or "_Section generation pending_",
            "",
            "---",
            "",
            "## 3. Low-Level Design (LLD)",
            self.lld.raw_markdown.strip() or "_Section generation pending_",
            "",
            "---",
            "",
            "## 4. Resilience, Concurrency & Security",
            self.resilience.raw_markdown.strip() or "_Section generation pending_",
            "",
            "---",
            "",
            "## 5. Developer Action Plan & Scaffolding",
            self.scaffolding.raw_markdown.strip() or "_Section generation pending_",
            "",
            "---",
            "",
            "_Generated by Autonomous System Design Agent_",
        ]
        return "\n".join(parts)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)
