"""
Validator for SQL DDL statements generated by agents.
Enforces non-empty schemas, foreign keys, indexes, and zero placeholders.
"""
from __future__ import annotations

import re
from typing import List, Tuple


class SQLValidator:
    FORBIDDEN_PLACEHOLDERS = [
        r"\.\.\.",
        r"--\s*TODO",
        r"--\s*rest of",
        r"/\*\s*TODO",
        r"/\*\s*rest of",
        r"<insert\s+",
        r"//\s*TODO",
    ]

    @classmethod
    def extract_sql_blocks(cls, markdown: str) -> List[str]:
        pattern = r"```sql\s*\n(.*?)\n```"
        return re.findall(pattern, markdown, flags=re.DOTALL)

    @classmethod
    def validate_sql(cls, sql_text: str) -> Tuple[bool, List[str]]:
        errors: List[str] = []
        cleaned = sql_text.strip()

        if not cleaned:
            return False, ["SQL block is completely empty."]

        # Check for forbidden placeholder patterns
        for placeholder_pattern in cls.FORBIDDEN_PLACEHOLDERS:
            match = re.search(placeholder_pattern, cleaned, re.IGNORECASE)
            if match:
                errors.append(
                    f"Forbidden placeholder or lazy omission found: '{match.group(0)}'. SQL DDL must be complete and copy-pasteable."
                )

        # Check for CREATE TABLE statement
        if not re.search(r"\bCREATE\s+TABLE\b", cleaned, re.IGNORECASE):
            errors.append("No 'CREATE TABLE' statements found in the SQL DDL.")

        # Check for PRIMARY KEY
        if not re.search(r"\bPRIMARY\s+KEY\b", cleaned, re.IGNORECASE):
            errors.append("No 'PRIMARY KEY' definitions found in tables.")

        # Check for INDEX creation
        has_index = bool(re.search(r"\bCREATE\s+(UNIQUE\s+)?INDEX\b", cleaned, re.IGNORECASE))
        if not has_index:
            errors.append("No explicit indexes ('CREATE INDEX ...') found. Production LLD requires performance indexes.")

        is_valid = len(errors) == 0
        return is_valid, errors

    @classmethod
    def validate_markdown(cls, markdown: str) -> Tuple[bool, List[str]]:
        blocks = cls.extract_sql_blocks(markdown)
        if not blocks:
            return False, ["No SQL code block found in markdown."]

        combined_sql = "\n\n".join(blocks)
        return cls.validate_sql(combined_sql)
