"""
Validator and linter for Mermaid.js diagrams generated by agents.
"""
from __future__ import annotations

import re
from typing import List, Tuple


class MermaidValidator:
    SUPPORTED_DIAGRAM_TYPES = (
        "graph TD",
        "graph LR",
        "graph TB",
        "flowchart TD",
        "flowchart LR",
        "flowchart TB",
        "sequenceDiagram",
        "classDiagram",
        "erDiagram",
        "stateDiagram-v2",
        "stateDiagram",
    )

    @classmethod
    def extract_mermaid_blocks(cls, markdown: str) -> List[str]:
        """Extracts content inside ```mermaid ... ``` code fences."""
        pattern = r"```mermaid\s*\n(.*?)\n```"
        return re.findall(pattern, markdown, flags=re.DOTALL)

    @classmethod
    def validate_block(cls, code: str) -> Tuple[bool, List[str]]:
        """Validates a single Mermaid diagram block for common syntax mistakes."""
        errors: List[str] = []
        cleaned = code.strip()

        if not cleaned:
            return False, ["Mermaid diagram block is empty."]

        # Check diagram header
        has_valid_header = any(
            cleaned.startswith(dtype) or cleaned.startswith(dtype.lower())
            for dtype in cls.SUPPORTED_DIAGRAM_TYPES
        )
        if not has_valid_header:
            first_line = cleaned.splitlines()[0] if cleaned.splitlines() else ""
            errors.append(f"Invalid or missing Mermaid diagram type header: '{first_line}'. Expected one of {cls.SUPPORTED_DIAGRAM_TYPES[:4]}...")

        # Check bracket balances
        bracket_pairs = [("[", "]"), ("(", ")"), ("{", "}")]
        for opening, closing in bracket_pairs:
            open_count = cleaned.count(opening)
            close_count = cleaned.count(closing)
            if open_count != close_count:
                errors.append(
                    f"Mismatched bracket count for '{opening}' and '{closing}' ({open_count} opening vs {close_count} closing)."
                )

        # Check sequenceDiagram specifics
        if cleaned.startswith("sequenceDiagram"):
            for line in cleaned.splitlines():
                line = line.strip()
                if (
                    line == "sequenceDiagram"
                    or line.startswith("sequenceDiagram")
                    or line.startswith("participant")
                    or line.startswith("actor")
                    or line.startswith("autonumber")
                    or line.startswith("alt")
                    or line.startswith("else")
                    or line.startswith("end")
                    or line.startswith("opt")
                    or line.startswith("loop")
                    or line.startswith("Note")
                    or line.startswith("critical")
                    or line.startswith("option")
                    or line.startswith("rect")
                    or not line
                ):
                    continue
                # If it's a message line, check that an arrow exists
                if not any(arrow in line for arrow in ("->>", "-->>", "->", "-->", "-)", "--)", "-x", "--x")):
                    if not line.startswith("%%"):
                        errors.append(f"Sequence diagram line has no recognized message arrow: '{line}'")

        # Check for unquoted node labels with special characters in graph TD / flowchart TD
        if cleaned.startswith("graph") or cleaned.startswith("flowchart"):
            for line in cleaned.splitlines():
                # Detect pattern like: Node[Foo (Bar)] where label isn't quoted
                # Skips cylinders [("...")] or properly quoted ["..."]
                unquoted_box = re.search(r'\w+\[(?!\(|\"|\')([^"\'\n]*?[()/<>&][^"\'\n]*?)\]', line)
                unquoted_cylinder = re.search(r'\w+\[\(\s*(?!\"|\')([^"\'\n]*?[()/<>&][^"\'\n]*?)\s*\)\]', line)
                if unquoted_box or unquoted_cylinder:
                    errors.append(f"Unquoted label with special characters may break Mermaid parser: '{line.strip()}'")

        is_valid = len(errors) == 0
        return is_valid, errors

    @classmethod
    def validate_markdown(cls, markdown: str) -> Tuple[bool, List[str]]:
        blocks = cls.extract_mermaid_blocks(markdown)
        if not blocks:
            return False, ["No Mermaid diagram blocks found in markdown."]
        
        all_errors: List[str] = []
        for idx, block in enumerate(blocks, 1):
            valid, errs = cls.validate_block(block)
            if not valid:
                for err in errs:
                    all_errors.append(f"Diagram #{idx}: {err}")

        return len(all_errors) == 0, all_errors
